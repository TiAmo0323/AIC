// Run through scripts/verify_motionlint_browser.py with Playwright CLI.
async page => {
  const cfg = __CONTEXT__;
  const checks = [];
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const importFile = async path => {
    const form = page.getByRole('region', {name:'导入动作数据', exact:true});
    if (!await form.count()) await page.getByRole('button',{name:'导入动作',exact:true}).click();
    await form.locator('input[type=file]').setInputFiles(path);
    const response = page.waitForResponse(r => r.url().endsWith('/v1/motionlint/imports') && r.request().method()==='POST');
    await form.getByRole('button',{name:'导入并检查',exact:true}).click();
    const result = await response;
    assert(result.ok(),'Import failed: '+await result.text());
    const data = await result.json();
    await page.locator('canvas').first().waitFor();
    await page.getByRole('button',{name:'修复全部可修复项',exact:true}).waitFor();
    return {...data,...data.task};
  };
  await page.goto(cfg.url);
  await page.setViewportSize({width:1440,height:1000});
  const raw = await importFile(cfg.defect);
  const timeline=page.getByRole('region',{name:'动作问题时间轴',exact:true});
  await timeline.getByRole('button').first().click();
  assert((await timeline.locator('.detail').innerText()).includes('阈值'),'No measured problem details');
  checks.push({name:'import_and_locate_actual_problem',status:'PASS',task_id:raw.task_id});
  await page.screenshot({path:cfg.output+'/01-locate.png',fullPage:true});
  await page.getByRole('button',{name:'修复全部可修复项',exact:true}).click();
  const link=page.getByRole('link',{name:'下载动作与完整报告 ZIP',exact:true});
  await link.waitFor({timeout:120000});
  const repairText=await page.locator('#motionlint-repair-summary').innerText();
  assert(repairText.includes('已接受'),'Known example was not repaired');
  const linked=page.getByRole('region',{name:'修复前后骨架联动比较',exact:true});
  await linked.getByRole('slider',{name:'帧',exact:true}).evaluate(el=>{el.value='100';el.dispatchEvent(new Event('input',{bubbles:true}));});
  await page.waitForFunction(()=>{
    const nodes=Array.from(document.querySelectorAll('.skeleton-comparison .preview-controls > span, .skeleton-comparison .linked-frame'));
    return nodes.length===2 && nodes.every(el=>el.textContent.startsWith('100 /'));
  });
  const labels=await linked.innerText();
  assert((labels.match(/100 \/ 299/g)||[]).length===2,'Comparison did not synchronize actual frames');
  const trials=page.locator('.repair-trials').first();
  await trials.locator('summary').click();
  assert((await trials.innerText()).includes('通过候选审查'),'Candidate audit unavailable');
  checks.push({name:'repair_acceptance_candidate_audit_and_linked_playback',status:'PASS',summary:repairText});
  await page.screenshot({path:cfg.output+'/02-repair.png',fullPage:true});
  const downloadPromise=page.waitForEvent('download');await link.click();
  const download=await downloadPromise;await download.saveAs(cfg.output+'/repair-bundle.zip');
  assert(!await download.failure(),'Bundle download failed');
  const htmlUrl=await page.getByRole('link',{name:'打开离线 HTML 报告',exact:true}).getAttribute('href');
  const htmlResponse=await page.request.get(htmlUrl);
  assert(htmlResponse.ok(),'HTML export failed');
  const html=await htmlResponse.text();
  const offline=await page.context().newPage();await offline.route('http**/*',route=>route.abort());
  await offline.goto('data:text/html;charset=utf-8,'+encodeURIComponent(html));
  assert((await offline.locator('body').innerText()).includes('MotionLint'),'Offline report missing');
  await offline.close();
  checks.push({name:'download_bundle_and_network_disabled_html',status:'PASS'});
  const reimportResponse=page.waitForResponse(r=>r.url().endsWith('/reimport') && r.request().method()==='POST');
  await page.getByRole('button',{name:'将 BVH 重新导入复检',exact:true}).click();
  const reimportResult=await (await reimportResponse).json();
  const reimported=reimportResult.task;
  assert(reimported.task_id!==raw.task_id,'Reimport overwrote the original');
  await page.getByRole('region',{name:'导入动作数据',exact:true}).getByText(/BVH/).first().waitFor();
  checks.push({name:'written_bvh_reimport',status:'PASS',task_id:reimported.task_id});
  const jobs=page.getByRole('region',{name:'持久化完整流程任务',exact:true});
  const pipelineResponse=page.waitForResponse(r=>r.url().endsWith('/v1/motionlint/pipeline')&&r.request().method()==='POST');
  await jobs.getByRole('button',{name:'检测 → 修复 → 实际 BVH 复检',exact:true}).click();
  const queued=await (await pipelineResponse).json();
  const queuedRow=jobs.locator('article').filter({hasText:queued.job_id.slice(0,8)});
  await queuedRow.getByText('产物已校验',{exact:false}).waitFor({timeout:120000});
  const state=await (await page.request.get(cfg.url+'/v1/motionlint/jobs/'+queued.job_id)).json();
  assert(state.status==='ready','Pipeline not ready');
  checks.push({name:'durable_pipeline_and_actual_export',status:'PASS',job_id:queued.job_id,quality_status:state.result.quality_status});
  const clean=await importFile(cfg.clean);
  const bad=await importFile(cfg.defect);
  await page.getByRole('combobox',{name:'选择基线任务',exact:true}).selectOption('import:'+clean.task_id);
  await page.getByRole('combobox',{name:'选择候选任务',exact:true}).selectOption('import:'+bad.task_id);
  const compareResponse=page.waitForResponse(r=>r.url().endsWith('/compare')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'比较',exact:true}).click();
  const compared=await (await compareResponse).json();
  assert(compared.status==='REGRESSION DETECTED','The introduced defect was not rejected');
  assert((await page.locator('#motionlint-regression').innerText()).includes('退步'),'Regression decision unavailable in UI');
  checks.push({name:'regression_rejection_in_actual_workbench',status:'PASS',comparison_status:compared.status});
  await page.screenshot({path:cfg.output+'/03-regression.png',fullPage:true});
  return {schema_version:3,status:'PASS',scope:'Automated actual browser operations; no human validation',checks};
}
